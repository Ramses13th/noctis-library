import {build} from 'esbuild';
import assert from 'node:assert/strict';
const data=new Map();
globalThis.localStorage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,String(v)),removeItem:k=>data.delete(k)};
const result=await build({entryPoints:['src/storage.ts'],bundle:true,platform:'node',format:'esm',write:false});
const s=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const [first]=s.getProfiles(),second=s.createProfile('Al doilea cititor');
const record={chapterId:'dot-meditation',position:.37,furthest:.61,completed:false,bookmarked:true,note:'Însemnare privată',updatedAt:123};
s.writeProgress(first.id,record);
assert.equal(s.readState(first.id).progress['dot-meditation'].note,'Însemnare privată');
assert.deepEqual(s.readState(second.id).progress,{});
s.writeProgress(first.id,{...record,position:.12,furthest:.2});
assert.equal(s.readState(first.id).progress['dot-meditation'].furthest,.61);
s.writeSettings(first.id,24,2.1);
s.writeActivePath(first.id,'atei-sceptici');
assert.equal(s.readState(first.id).settings.activePathId,'atei-sceptici');
assert.equal(s.readState(second.id).settings.activePathId,null);
assert.throws(()=>s.writeActivePath(first.id,'unknown-path'));
const exported=s.backupProfile(first);
assert.equal(exported.settings.fontSize,24);
assert.equal(s.importProgress(second.id,JSON.stringify(exported)),1);
assert.equal(s.readState(second.id).progress['dot-meditation'].bookmarked,true);
assert.equal(s.readState(second.id).settings.fontSize,24);
assert.equal(s.readState(second.id).settings.activePathId,'atei-sceptici');
const before=JSON.stringify(s.readState(second.id));
assert.throws(()=>s.importProgress(second.id,JSON.stringify({progress:{'dot-meditation':{...record,note:5}}})));
assert.equal(JSON.stringify(s.readState(second.id)),before);
assert.throws(()=>s.importProgress(second.id,'{broken JSON'));
assert.equal(s.importProgress(second.id,JSON.stringify({progress:{'unknown-chapter':record}})),0);
s.activateProfile(first.id);
assert.equal(s.getActiveProfile(s.getProfiles()).id,first.id);
console.log('PASS: profile isolation, persistent progress, furthest position, settings, export/import, invalid-file protection, profile selection.');
